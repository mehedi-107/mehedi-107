// README.md: the terminal's segments stacked into one window. Each segment is a
// <picture> (GitHub picks light or dark) inside a link. `align="left"` floats
// every segment: full-width floats stack flush at any scale, where inline images
// would pick up line-height gaps once phones shrink them.
import { esc } from './lib/svg.mjs';

export function readme({ profile }, segments, sizes) {
  const url = (name, theme) => `${profile.assetBase}${name}-${theme}.svg`;
  const pic = (name, alt) =>
    `<picture>` +
    `<source media="(prefers-color-scheme: dark)" srcset="${url(name, 'dark')}">` +
    `<source media="(prefers-color-scheme: light)" srcset="${url(name, 'light')}">` +
    `<img alt="${esc(alt)}" src="${url(name, 'light')}" width="${sizes[name]}" align="left">` +
    `</picture>`;
  const rows = segments.map((s) => `<a href="${s.href ?? profile.repositories}">${pic(`term-${s.id}`, s.alt)}</a>`);

  return `<!--
  Generated by scripts/build.mjs. Edit scripts/content.mjs, then run:
    npm install
    npm run build
-->

<p>
${rows.join('\n')}
</p>
`;
}
